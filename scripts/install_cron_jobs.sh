#!/usr/bin/env bash
# Install CareerOps cron jobs.
#
# IMPORTANT: Countries / work modes are NO LONGER hardcoded here.
# They live in config.json (per-user, gitignored). This scheduler only
# decides *when* to run and *whether* to fire the daily digest.
# The wrapper (run_careerops.sh) reads config.json and scans whatever
# targets are defined there.
#
# Usage: ./install_cron_jobs.sh [install|remove|list|test]

set -uo pipefail

PROJECT="/home/castro/Projects/CareerOps"
WRAPPER="$PROJECT/scripts/run_careerops.sh"
LOGDIR="$PROJECT/logs"
mkdir -p "$LOGDIR"

# Crontab marker comments for identification
MARKER_START="# >>> CAREEROPS CRON JOBS START <<<"
MARKER_END="# >>> CAREEROPS CRON JOBS END <<<"

# Define schedules: "minute hour day month weekday [digest]"
#   - Times are the only thing this script controls.
#   - "digest" (optional) => fire the daily Telegram digest at the end.
#     Use it on EXACTLY ONE job per day to avoid digest spam.
#   - The wrapper reads config.json to decide WHICH countries to scan.
# Format: minute hour day month weekday [digest]
readonly SCHEDULES=(
    # Frequent runs (e.g. high-priority remote-only home country)
    "0 6 * * *"
    "0 11 * * *"
    "0 16 * * *"
    "0 21 * * * digest"   # last run of day fires digest

    # European / North-American morning sweep
    "0 8 * * *"
    "0 9 * * *"

    # Late-evening global sweep
    "0 23 * * *"
)

show_current() {
    crontab -l 2>/dev/null | sed -n "/$MARKER_START/,/$MARKER_END/p" || echo "(no CareerOps cron jobs installed)"
}

install_jobs() {
    # Remove existing CareerOps entries first
    crontab -l 2>/dev/null | grep -v "$MARKER_START" | grep -v "$MARKER_END" | grep -v "run_careerops.sh" > /tmp/careerops_crontab.tmp || true

    # Add new entries
    {
        echo "$MARKER_START"
        echo "# Auto-generated by install_cron_jobs.sh on $(date)"
        echo "# Countries/work-modes come from config.json (NOT from here)."
        echo "# Edit SCHEDULES array in this script to change run times only."
        echo ""

        for entry in "${SCHEDULES[@]}"; do
            # Parse: first 5 fields are cron, optional 6th is "digest"
            read -ra parts <<< "$entry"
            cron_expr="${parts[0]} ${parts[1]} ${parts[2]} ${parts[3]} ${parts[4]}"
            last_idx=$((${#parts[@]} - 1))
            if [[ "${parts[last_idx]}" == "digest" ]]; then
                digest_flag="digest"
            else
                digest_flag=""
            fi

            # Wrapper reads config.json for the actual country list.
            # Log file is created at runtime (per-day, no country in name
            # since the run scans whatever config.json defines).
            log_file="$LOGDIR/careerops-\$(date +\\%Y\\%m\\%d).log"
            echo "$cron_expr $WRAPPER $digest_flag >> $log_file 2>&1"
        done

        echo ""
        echo "$MARKER_END"
    } >> /tmp/careerops_crontab.tmp

    crontab /tmp/careerops_crontab.tmp
    rm -f /tmp/careerops_crontab.tmp
    echo "✅ Cron jobs installed successfully"
    show_current
}

remove_jobs() {
    crontab -l 2>/dev/null | grep -v "$MARKER_START" | grep -v "$MARKER_END" | grep -v "run_careerops.sh" | crontab -
    echo "✅ CareerOps cron jobs removed"
}

test_job() {
    echo "Testing a manual run (wrapper reads config.json for countries)..."
    if [ "${1:-}" = "digest" ]; then
        "$WRAPPER" digest
    else
        "$WRAPPER"
    fi
}

case "${1:-install}" in
    install)
        install_jobs
        ;;
    remove)
        remove_jobs
        ;;
    list)
        show_current
        ;;
    test)
        test_job "${2:-}"
        ;;
    *)
        echo "Usage: $0 {install|remove|list|test [digest]}"
        exit 1
        ;;
esac
