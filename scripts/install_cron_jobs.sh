#!/usr/bin/env bash
# Install CareerOps cron jobs for multiple countries with different schedules
# Usage: ./install_cron_jobs.sh [install|remove|list|test]

set -uo pipefail

PROJECT="/home/castro/Projects/CareerOps"
WRAPPER="$PROJECT/scripts/run_careerops.sh"
LOGDIR="$PROJECT/logs"
mkdir -p "$LOGDIR"

# Crontab marker comments for identification
MARKER_START="# >>> CAREEROPS CRON JOBS START <<<"
MARKER_END="# >>> CAREEROPS CRON JOBS END <<<"

# Define schedules: "minute hour day month weekday country [digest_flag]"
# digest_flag: "" (no digest) or "digest" (fire digest at end)
# Only ONE job per day should have digest flag to avoid spam
# Format: minute hour day month weekday country [digest]
readonly SCHEDULES=(
    # Brazil - 4x per day (high priority, remote only)
    "0 6 * * * Brazil"
    "0 11 * * * Brazil"
    "0 16 * * * Brazil"
    "0 21 * * * Brazil digest"  # Last run of day fires digest

    # Netherlands - 1x per day (European morning)
    "0 8 * * * Netherlands"

    # Ireland - 1x per day
    "0 9 * * * Ireland"

    # Poland - 1x per day
    "0 9 * * * Poland"

    # Germany - 1x per day
    "0 8 * * * Germany"

    # United Kingdom - 1x per day
    "0 9 * * * United Kingdom"

    # Switzerland - 1x per day
    "0 9 * * * Switzerland"

    # Canada - 1x per day (North American morning)
    "0 8 * * * Canada"

    # Worldwide - 1x per day (late evening for global coverage)
    "0 23 * * * worldwide"
)

show_current() {
    crontab -l 2>/dev/null | sed -n "/$MARKER_START/,/$MARKER_END/p" || echo "(no CareerOps cron jobs installed)"
}

install_jobs() {
    # Remove existing CareerOps entries first
    crontab -l 2>/dev/null | grep -v "$MARKER_START" | grep -v "$MARKER_END" | grep -v "run_careerops.sh" > /tmp/careerops_crontab.tmp || true

    # Add new entries
    {
        echo "$MARKER_START"
        echo "# Auto-generated by install_cron_jobs.sh on $(date)"
        echo "# Edit SCHEDULES array in this script to modify schedules"
        echo ""

        for entry in "${SCHEDULES[@]}"; do
                    # Parse: first 5 fields are cron, rest is country name + optional digest
                    # Using array to properly handle multi-word country names
                    read -ra parts <<< "$entry"
                    cron_expr="${parts[0]} ${parts[1]} ${parts[2]} ${parts[3]} ${parts[4]}"
                    # Country is everything from index 5 to second-to-last (or last if no digest)
                    # Check if last element is "digest"
                    last_idx=$((${#parts[@]} - 1))
                    if [[ "${parts[last_idx]}" == "digest" ]]; then
                        digest_flag="digest"
                        # Country is parts[5] to parts[last_idx-1]
                        country=$(IFS=' '; echo "${parts[*]:5:last_idx-5}")
                    else
                        digest_flag=""
                        # Country is parts[5] to end
                        country=$(IFS=' '; echo "${parts[*]:5}")
                    fi

                    # Escape country for shell
                    country_escaped=$(printf '%q' "$country")

                    # Use a wrapper that creates dated log files at runtime
                    log_file="$LOGDIR/careerops-\$(echo \"$country_escaped\" | tr '[:upper:]' '[:lower:]' | tr ' ' '-')-\$(date +\\%Y\\%m\\%d).log"
                    echo "$cron_expr $WRAPPER $country_escaped $digest_flag >> $log_file 2>&1"
                done

        echo ""
        echo "$MARKER_END"
    } >> /tmp/careerops_crontab.tmp

    crontab /tmp/careerops_crontab.tmp
    rm -f /tmp/careerops_crontab.tmp
    echo "✅ Cron jobs installed successfully"
    show_current
}

remove_jobs() {
    crontab -l 2>/dev/null | grep -v "$MARKER_START" | grep -v "$MARKER_END" | grep -v "run_careerops.sh" | crontab -
    echo "✅ CareerOps cron jobs removed"
}

test_job() {
    if [ -z "${1:-}" ]; then
        echo "Usage: $0 test <country>"
        exit 1
    fi
    echo "Testing run for country: $1"
    "$WRAPPER" "$1"
}

case "${1:-install}" in
    install)
        install_jobs
        ;;
    remove)
        remove_jobs
        ;;
    list)
        show_current
        ;;
    test)
        test_job "${2:-}"
        ;;
    *)
        echo "Usage: $0 {install|remove|list|test <country>}"
        exit 1
        ;;
esac